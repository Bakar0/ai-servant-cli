// The generated documents under a workspace's `docs/agents/`: the contract servant publishes to
// whatever instruction set is installed.
//
// These are not configuration for any one skill. They are the board's public interface, written as
// prose because that is the only interface a skill has: a skill that has never seen this CLI reads
// `issue-tracker.md` and can file, label, block, claim, comment on and close work without reading
// servant's source. servant pre-writes them per workspace because a workspace root is not a git
// clone — nothing here can be auto-detected — and because the tracker is servant's own local board
// rather than any repo's GitHub Issues.
//
// They are **load-bearing**: the map/child-ticket vocabulary lives here rather than in code, so
// prose is part of the migration surface (ADR-0011). They used to be written once and never
// refreshed, which meant an existing workspace would keep instructing agents to run `gh issue
// create` forever. They now carry a content stamp, and `writeStamped` rewrites them when it moves.

import { contentStamp } from "./content-stamp.ts";

export const AGENT_SKILLS_MARKER = "<!-- servant:agent-skills -->";

/** Marks a servant-generated agent doc, and carries the hash of the content it was generated from. */
const STAMP_PREFIX = "<!-- servant:agent-doc v=";

/**
 * A generated doc with its content stamp on the first line.
 *
 * The stamp is derived from the content rather than hand-bumped, so there is no version constant to
 * forget: change the prose and every workspace picks it up on its next spawn. It is also what makes
 * the version legible in the file itself, so two workspaces can be compared at a glance.
 */
export function stampDoc(body: string): string {
  return `${STAMP_PREFIX}${contentStamp(body)} — generated by servant; edits here are overwritten -->\n${body}`;
}

/** The board's public contract (docs/agents/issue-tracker.md). */
export function renderIssueTrackerDoc(workspace: string): string {
  return stampDoc(`# Issue tracker: the servant board

Tickets, specs and plans for this workspace live on **servant's own board** — a local SQLite
database at the servant root, read and written by \`servant\` commands. There is no GitHub, no
\`gh\`, no account and no network: every operation below works offline, and works whether or not the
board viewer is open.

**This file is the whole interface.** It is the contract servant publishes to whatever is reading
it — a skill, a command, a subagent, a human. If you have never seen this CLI before, everything you
need to file, find, label, block, claim, comment on and close work is written down here; you do not
need to read servant's source, and you should not guess at flags that are not listed.

Each workspace is a board of its own, so ticket numbers are small and board-scoped. This workspace's
board is \`${workspace}\`. Every command below defaults to the board of the workspace you are
running in — pass \`--ws ${workspace}\` explicitly when you are not.

## If your instructions were written for a different tracker

Most task-shaping instructions in the wild assume GitHub Issues. Translate them rather than trying
to make \`gh\` work — there is no repository behind this board and no network call to make.

| Written as                           | Do this instead                                 |
| ------------------------------------ | ----------------------------------------------- |
| "publish to the issue tracker"       | \`servant ticket new --title "..." --body "..."\` |
| "fetch the issue"                    | \`servant ticket show <n>\`                       |
| "list the open issues"               | \`servant tasks\`                                 |
| "comment on the issue"               | \`servant ticket comment <n> --body "..."\`       |
| "apply the label"                    | \`servant ticket label <n> --add "<label>"\`      |
| "close the issue"                    | \`servant ticket close <n>\`                      |
| a sub-issue, or a task-list child    | \`servant ticket new --parent <n>\`               |
| a \`Blocked by: #12\` line in the body | \`servant ticket block <n> --on 12\`              |
| an assignee                          | a Claim — \`servant claim <n> --session <name>\`  |

## Operations

- **Create a ticket**: \`servant ticket new --title "..." --body "..." --labels "spec"\`
  (heredoc for multi-line bodies). It prints the new number; add \`--json\` to read it back
  programmatically. Labels are freeform strings — nothing needs creating first. \`--status\` sets the
  starting state and \`--parent <n>\` hangs it off a map (see below).
- **Read a ticket**: \`servant ticket show <number>\` — body, labels, claim, both directions of its
  blocking edges, and its comments. Add \`--history\` for how it got there: when it was filed, and
  every label and status change since. \`--json\` for a machine-readable form.
- **List this workspace's tickets**: \`servant tasks --ws ${workspace}\`. Add
  \`--state closed\` or \`--state all\` for closed ones too, and \`--frontier --json\` to get what is
  dispatchable, sorted into \`ready\`, \`inFlight\`, \`stale\` and \`blocked\`.
- **Comment**: \`servant ticket comment <number> --body "..."\`. Add \`--session <name>\` to attribute
  it to a session. Findings, answers and handoffs belong on the ticket, not in a scratch file.
- **Apply / remove labels**: \`servant ticket label <number> --add "a,b" --remove "c"\`.
- **Move between states**: \`servant ticket status <number> <todo|in_progress|in_review|done>\`.
- **Close**: \`servant ticket close <number> --comment "..."\`. Anything it was blocking becomes
  ready immediately.

\`blocked\` and \`ready\` are **not** states you set — both are derived from open dependencies, so
they can never disagree with what \`servant tasks --frontier\` reports.

By convention a ticket is labeled \`spec\` when it holds a specification and \`ticket\` when it is a
tracer-bullet unit of work, plus any triage label (see \`triage-labels.md\`). Nothing in the board
enforces this; it is what the other surfaces here expect to read.

## Blocking

One representation, and it is a real graph:

- **Record a blocker**: \`servant ticket block <number> --on <blocker>\`. Add
  \`--on-ws <workspace>\` when the blocker is on another workspace's board — cross-board
  dependencies are expressible, and stored against a global id so renumbering cannot break them.
- **Drop one**: \`servant ticket unblock <number> --on <blocker>\`.
- A dependency that would create a cycle is **rejected when you add it**. Do not write blocking
  into the body as prose — a \`Blocked by:\` line in a ticket body is read by nothing.
- \`servant ticket show\` reports both directions: what blocks this, and what this blocks.

## Claims

A Claim is how the board says which session is carrying a ticket. It is the board's answer to
"assignee", and it is what makes a ticket disappear from the dispatchable set.

- **Take it**: \`servant claim <number> --session <name>\`, conventionally named
  \`${workspace}-t<number>\`. Idempotent — re-claiming one you already hold is not an error.
- **Release it**: \`servant claim <number> --release --session <name>\`, as soon as the work is
  done or abandoned, so the ticket returns to the frontier.
- **History**: \`servant claim <number> --history\`.

A Claim is not written for you. Spawning a session does not claim anything, so a Claim is an
explicit act. Claiming someone else's ticket is a recorded transfer — never work a ticket you have
not claimed.

## Maps and child tickets

When a piece of work is too large to specify up front, the board carries it as a **map**: one ticket
holding the framing, with **child** tickets hanging off it. The viewer renders a map specially, and
it recognises both parts by label, so the strings below are exact.

- **Map**: \`servant ticket new --labels "wayfinder:map" --title "..." --body "..."\`. The body's
  \`## \` sections are parsed and rendered as the frame; use exactly these headings, and expect a
  missing one to read as empty rather than to fail:

  \`\`\`
  ## Destination
  ## Out of scope
  ## Decisions so far
  ## Not yet specified
  \`\`\`

- **Child ticket**: \`servant ticket new --parent <map> --labels "wayfinder:<type>"\` where
  \`<type>\` is \`research\`, \`prototype\`, \`grilling\` or \`task\`. The parent link is structural,
  not a line in the body; a child with no type label reads as a \`task\`.
- **Blocking between children**: \`servant ticket block <child> --on <other-child>\`.
- **Frontier query**: \`servant tasks --frontier --json\` — its \`ready\` bucket is exactly the
  unblocked, unclaimed set. Do not re-derive it by reading bodies.
- **Claim**: \`servant claim <n> --session <name>\` (see Claims above).
- **Resolve a child**: \`servant ticket comment <n> --body "<answer>"\`, then
  \`servant ticket close <n>\`, then append a pointer to the map's \`## Decisions so far\`.

Edit map prose one section at a time rather than rewriting the whole body, so two sessions working
the same map cannot silently overwrite each other.
`);
}

/** Domain-doc consumer rules (docs/agents/domain.md) — servant adopts CONTEXT.md + docs/adr/. */
export function renderDomainDoc(): string {
  return stampDoc(`# Domain docs

Where this workspace keeps its domain knowledge, and when to read it. This is the contract servant
publishes: whatever is installed, these two locations are the answer to "what does this project mean
by that word, and what has already been decided?".

## Before exploring, read these

- **\`CONTEXT.md\`** at the workspace root — the shared language / domain glossary. Each entry
  defines a term and, where it matters, lists the near-synonyms to avoid.
- **\`docs/adr/\`** — numbered architecture decision records. Read the ones that touch the area you
  are about to work in.

If either does not exist yet, **proceed silently**. They are created lazily, when a term or a
decision actually gets resolved — never as empty scaffolding, and never as a precondition for work.

## File structure

\`\`\`
<workspace>/
├── CONTEXT.md
├── docs/adr/
│   ├── 0001-<slug>.md
│   └── 0002-<slug>.md
└── repos/            ← mounted repo worktrees
\`\`\`

## Use the glossary's vocabulary

When your output names a domain concept — a ticket title, a refactor proposal, a hypothesis, a test
name — use the term as defined in \`CONTEXT.md\`. If the concept is not in the glossary yet, that is
a signal: either you are inventing language the project does not use (reconsider), or there is a
real gap worth recording.

## Flag ADR conflicts

If your output contradicts an existing ADR, surface it explicitly rather than quietly picking a
side:

> _Contradicts ADR-0007 (event-sourced orders) — but worth reopening because…_

A new decision goes in a new ADR that names the one it supersedes. Do not rewrite a settled record.
`);
}

/** Triage labels (docs/agents/triage-labels.md) — the five canonical roles. */
export function renderTriageLabelsDoc(): string {
  return stampDoc(`# Triage labels

The five triage roles this board recognises, and the label string each one is written as. These are
canonical: an instruction that names a triage role by any other wording means one of these five.

| Label             | Meaning                                 |
| ----------------- | --------------------------------------- |
| \`needs-triage\`    | Needs evaluation                        |
| \`needs-info\`      | Waiting on more information             |
| \`ready-for-agent\` | Fully specified, ready for an AFK agent |
| \`ready-for-human\` | Requires human implementation           |
| \`wontfix\`         | Will not be actioned                    |

Apply one with \`servant ticket label <n> --add "<label>"\`; labels are freeform on the board, so
nothing needs creating first. A ticket carries at most one triage label — replace rather than
accumulate: \`servant ticket label <n> --add "ready-for-agent" --remove "needs-triage"\`.

These are about *readiness*, not progress. Where a ticket sits on the board is its status
(\`servant ticket status\`), and whether it is dispatchable is derived from its blockers and its
Claim — see \`issue-tracker.md\`.
`);
}

